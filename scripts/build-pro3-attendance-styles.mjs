import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve('tailwindcss-pro3'))('postcss');
import tailwind from 'tailwindcss-pro3';
import config from '../src/modules/attendance/pro3/ui/tailwind.config.mjs';
const result = await postcss([tailwind(config)]).process('@tailwind base; @tailwind utilities;', { from: undefined });
const root = postcss.parse(result.css);
root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap(selector => selector === '*' ? ['.pro3-attendance', '.pro3-attendance *'] : [`.pro3-attendance ${selector}`]);
});
await fs.writeFile('src/modules/attendance/pro3/ui/legacy-utilities.css', '/* Generated by scripts/build-pro3-attendance-styles.mjs; original PRO3 Tailwind 3 utilities. */\n' + root.toString());
