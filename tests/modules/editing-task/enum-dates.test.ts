import { describe, expect, it } from "vitest";
import { enumDates } from "@/app/(dashboard)/editing/_lib/enum-dates";

// 回归：2026-07-06（周一）起的一周，UTC+8 下曾整体倒退一天（7/5–7/11），
// 导致甘特表头周一标成 7/5、周日 7/12 列丢失。
describe("enumDates", () => {
  it("枚举整周日期不受本机时区影响", () => {
    expect(enumDates("2026-07-06", "2026-07-12")).toEqual([
      "2026-07-06",
      "2026-07-07",
      "2026-07-08",
      "2026-07-09",
      "2026-07-10",
      "2026-07-11",
      "2026-07-12",
    ]);
  });

  it("跨月枚举", () => {
    expect(enumDates("2026-06-29", "2026-07-05")).toEqual([
      "2026-06-29",
      "2026-06-30",
      "2026-07-01",
      "2026-07-02",
      "2026-07-03",
      "2026-07-04",
      "2026-07-05",
    ]);
  });

  it("单日区间返回自身", () => {
    expect(enumDates("2026-07-06", "2026-07-06")).toEqual(["2026-07-06"]);
  });
});
